export const brandSlug = (name: string) =>
  name.toLowerCase().replace(/&/g, '-').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

/** Марки, по которым в каталоге есть хотя бы одна позиция. */
export function allBrands(): (Brand & { cars: Car[] })[] {
  const byName = new Map<string, Car[]>();
  for (const car of cars) {
    const list = byName.get(car.brand) ?? [];
    list.push(car);
    byName.set(car.brand, list);
  }

  return [...byName.entries()]
    .map(([name, list]) => {
      const slug = brandSlug(name);
      const rich = BRANDS.find((b) => b.slug === slug);
      if (rich) return { ...rich, cars: list };
      const plain = PLAIN[slug];
      return {
        slug,
        name,
        aliases: [],
        country: plain?.country ?? 'Китай, Корея, США и Европа',
        tagline: plain?.tagline ?? `Автомобили ${name} под заказ с проверкой и доставкой в Беларусь`,
        about: [
          `${name} привозим под заказ с зарубежных площадок. Подбираем модель, год и комплектацию под ваш запрос и бюджет, проверяем автомобиль до выкупа и присылаем фотоотчёт.`,
          'В стоимость под ключ входят покупка, страхование на время перевозки, доставка, таможенное оформление и подготовка полного пакета документов для постановки на учёт в Беларуси.',
        ],
        gap: 0,
        cars: list,
      } satisfies Brand & { cars: Car[] };
    })
    .sort((a, b) => b.cars.length - a.cars.length || a.name.localeCompare(b.name));
}

export const getBrand = (slug: string) => allBrands().find((b) => b.slug === slug);

/** Марки для блока «Популярные» — по объёму спроса, затем по числу позиций. */
export const popularBrands = () =>
  allBrands()
    .slice()
    .sort((a, b) => b.gap - a.gap || b.cars.length - a.cars.length)
    .slice(0, 12);
